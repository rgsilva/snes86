#!/usr/bin/env python3
"""Generate the Pico keyboard's byte -> BIOS key table.

The adapter (SNOS's Pico W firmware, on controller port 2) sends what
its US layout already translated: ASCII, Ctrl-letter as 1-26, and
$1C-$1F for the arrows. pk_keytab turns each byte back into the word
INT 16h returns, (scancode << 8) | ascii; pk_modtab says which
modifier a guest that hooked INT 9 has to see held around the key
(bit0 Shift, bit1 Ctrl). A zero word is a byte with no key."""
import os
import sys

out = sys.argv[1] if len(sys.argv) > 1 else "build"

SCAN = {}
for i, c in enumerate("1234567890-="):
    SCAN[c] = 0x02 + i
for row, base in (("qwertyuiop[]", 0x10), ("asdfghjkl;'`", 0x1E),
                  ("zxcvbnm,./", 0x2C)):
    for i, c in enumerate(row):
        SCAN[c] = base + i
SCAN["\\"] = 0x2B
SCAN[" "] = 0x39

SHIFTED = dict(zip("!@#$%^&*()_+{}|:\"~<>?",
                   "1234567890-=[]\\;'`,./"))

SHIFT, CTRL = 1, 2
key = [0] * 128
mod = [0] * 128

for b in range(1, 27):                    # Ctrl-A .. Ctrl-Z
    key[b] = SCAN[chr(b + 0x60)] << 8 | b
    mod[b] = CTRL
for b in range(0x20, 0x7F):
    c = chr(b)
    if c in SCAN:
        key[b] = SCAN[c] << 8 | b
    elif c.isupper():
        key[b], mod[b] = SCAN[c.lower()] << 8 | b, SHIFT
    else:
        key[b], mod[b] = SCAN[SHIFTED[c]] << 8 | b, SHIFT

# the keys that share a control code: the firmware means the key
for b, word in ((0x08, 0x0E08),           # Backspace
                (0x09, 0x0F09),           # Tab
                (0x0A, 0x1C0D),           # Enter (the firmware sends LF)
                (0x0D, 0x1C0D),
                (0x1B, 0x011B),           # Esc
                (0x1C, 0x4800),           # up
                (0x1D, 0x5000),           # down
                (0x1E, 0x4B00),           # left
                (0x1F, 0x4D00)):          # right
    key[b], mod[b] = word, 0

os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "pickeys.asm"), "w") as f:
    f.write("; generated by mkpickeys.py\npk_keytab:\n")
    for i in range(0, 128, 8):
        f.write("    .dw " + ", ".join("$%04X" % v for v in key[i:i+8]) + "\n")
    f.write("pk_modtab:\n")
    for i in range(0, 128, 16):
        f.write("    .db " + ", ".join("%d" % v for v in mod[i:i+16]) + "\n")
print("pickeys.asm: %d keys" % sum(1 for v in key if v))
