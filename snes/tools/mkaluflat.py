#!/usr/bin/env python3
"""Generate flattened ALU op bodies (M13 perf round 3).

The grouped forms pay a stub (ldx/stx aluIDX/jmp), a table dispatch
(ldx aluIDX + jsr (alu_tab,x) + rts), an aluIDX reload + CMP test, and
jsr/rts layers around rm_read/rm_write — ~79 cycles of pure overhead
per rm-ALU instruction. These bodies inline the whole chain: decode,
operand fetch, executor, writeback (none for CMP), straight to
step_next. Semantics mirror cpu.asm's alu_* executors bit for bit —
the parity suite is the referee. grp1 imm forms and ali8/axi16 keep
the original table path.

Output: build/aluflat.asm, .INCLUDEd by cpu.asm (both parity and DOS
builds — parity validates the flattening).
"""
import sys

OPS = [
    ("add", 0), ("or", 1), ("adc", 2), ("sbb", 3),
    ("and", 4), ("sub", 5), ("xor", 6), ("cmp", 7),
]


def exec16(op, tag):
    if op in ("add", "adc"):
        pre = ["jsr cf_to_carry"] if op == "adc" else ["clc"]
        return pre + [
            "lda lfA", "adc lfB", "sta lfR",
            "lda #0", "rol a", "sta lfCF",
            "lda #LF_ADD16", "sta lfKIND", "lda lfR"]
    if op in ("sub", "sbb", "cmp"):
        pre = ["jsr cf_to_carry_inv"] if op == "sbb" else ["sec"]
        return pre + [
            "lda lfA", "sbc lfB", "sta lfR",
            "lda #0", "rol a", "eor #$0001", "sta lfCF",
            "lda #LF_SUB16", "sta lfKIND", "lda lfR"]
    mn = {"or": "ora", "and": "and", "xor": "eor"}[op]
    return ["lda lfA", f"{mn} lfB", "sta lfR",
            "lda #LF_LOG16", "sta lfKIND", "lda lfR"]


def exec8(op, tag):
    if op in ("add", "adc"):
        pre = ["jsr cf_to_carry"] if op == "adc" else ["clc"]
        return pre + [
            "lda lfA", "adc lfB", "sta lfR",
            "and #$0100", "xba", "and #$00FF", "sta lfCF",
            "lda lfR", "and #$00FF", "sta lfR",
            "lda #LF_ADD8", "sta lfKIND", "lda lfR"]
    if op in ("sub", "sbb", "cmp"):
        pre = ["jsr cf_to_carry_inv"] if op == "sbb" else ["sec"]
        return pre + [
            "lda lfA", "sbc lfB", "sta lfR",
            "lda #0", "rol a", "eor #$0001", "sta lfCF",
            "lda lfR", "and #$00FF", "sta lfR",
            "lda #LF_SUB8", "sta lfKIND", "lda lfR"]
    mn = {"or": "ora", "and": "and", "xor": "eor"}[op]
    return ["lda lfA", f"{mn} lfB", "sta lfR",
            "lda #LF_LOG8", "sta lfKIND", "lda lfR"]


def body(lines):
    return "\n".join("    " + l for l in lines)


# 16-bit memory operands go through rd16m/wr16m under SA1: a word at the
# WRAM top ($7F:FFFF) straddles into BW-RAM and a bare [mPTR] would
# read/write the system-area mirror instead (cpu.asm rd16m has the map).
# 8-bit operands can't straddle and stay bare.
RD16 = [".IFDEF SA1", "jsr rd16m", ".ELSE", "lda [mPTR]", ".ENDIF"]
WR16 = [".IFDEF SA1", "jsr wr16m", ".ELSE", "sta [mPTR]", ".ENDIF"]


out = ["; generated by tools/mkaluflat.py — do not edit", ""]

for name, idx in OPS:
    o_rmr8 = idx * 8
    o_rmr16 = idx * 8 + 1
    o_rrm8 = idx * 8 + 2
    o_rrm16 = idx * 8 + 3
    wb = name != "cmp"

    # --- op rm16, r16
    t = f"f{o_rmr16:02X}"
    out.append(f"op{o_rmr16:02X}:                       ; {name} rm16, r16 (flat)")
    out.append(body(["jsr decode_modrm", "lda mISREG", f"bne _{t}r"]
                    + RD16
                    + ["sta lfA",
                       "ldx mREG", "lda.b 0,x", "sta lfB"]
                    + exec16(name, t)
                    + (WR16 if wb else [])
                    + ["jmp step_next"]))
    out.append(f"_{t}r:")
    out.append(body(["ldx mRM", "lda.b 0,x", "sta lfA",
                     "ldx mREG", "lda.b 0,x", "sta lfB"]
                    + exec16(name, t)
                    + (["ldx mRM", "sta.b 0,x"] if wb else [])
                    + ["jmp step_next"]))
    out.append("")

    # --- op r16, rm16
    t = f"f{o_rrm16:02X}"
    out.append(f"op{o_rrm16:02X}:                       ; {name} r16, rm16 (flat)")
    out.append(body(["jsr decode_modrm", "lda mISREG", f"bne _{t}r"]
                    + RD16
                    + [f"bra _{t}c"]))
    out.append(f"_{t}r:")
    out.append(body(["ldx mRM", "lda.b 0,x"]))
    out.append(f"_{t}c:")
    out.append(body(["sta lfB", "ldx mREG", "lda.b 0,x", "sta lfA"]
                    + exec16(name, t)
                    + (["ldx mREG", "sta.b 0,x"] if wb else [])
                    + ["jmp step_next"]))
    out.append("")

    # --- op rm8, r8
    t = f"f{o_rmr8:02X}"
    out.append(f"op{o_rmr8:02X}:                       ; {name} rm8, r8 (flat)")
    out.append(body(["jsr decode_modrm", "jsr fixup8", "lda mISREG",
                     f"bne _{t}r",
                     "lda [mPTR]", "and #$00FF", "sta lfA",
                     "ldx mREG", "lda.b 0,x", "and #$00FF", "sta lfB"]
                    + exec8(name, t)
                    + (["sep #$20", "sta [mPTR]", "rep #$20"] if wb else [])
                    + ["jmp step_next"]))
    out.append(f"_{t}r:")
    out.append(body(["ldx mRM", "lda.b 0,x", "and #$00FF", "sta lfA",
                     "ldx mREG", "lda.b 0,x", "and #$00FF", "sta lfB"]
                    + exec8(name, t)
                    + (["ldx mRM", "sep #$20", "sta.b 0,x", "rep #$20"]
                       if wb else [])
                    + ["jmp step_next"]))
    out.append("")

    # --- op r8, rm8
    t = f"f{o_rrm8:02X}"
    out.append(f"op{o_rrm8:02X}:                       ; {name} r8, rm8 (flat)")
    out.append(body(["jsr decode_modrm", "jsr fixup8", "lda mISREG",
                     f"bne _{t}r",
                     "lda [mPTR]", f"bra _{t}c"]))
    out.append(f"_{t}r:")
    out.append(body(["ldx mRM", "lda.b 0,x"]))
    out.append(f"_{t}c:")
    out.append(body(["and #$00FF", "sta lfB",
                     "ldx mREG", "lda.b 0,x", "and #$00FF", "sta lfA"]
                    + exec8(name, t)
                    + (["ldx mREG", "sep #$20", "sta.b 0,x", "rep #$20"]
                       if wb else [])
                    + ["jmp step_next"]))
    out.append("")

with open(sys.argv[1], "w") as f:
    f.write("\n".join(out) + "\n")
print(f"{sys.argv[1]}: {len(OPS) * 4} flattened ALU bodies")
