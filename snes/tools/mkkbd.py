#!/usr/bin/env python3
"""Generate the on-screen keyboard layout: 5 rows of text, a 5x64
navigation grid (cell -> key index), per-key records, and the shift
delta list (cells whose glyph changes while sticky shift is latched)."""
import os
import sys

out = sys.argv[1] if len(sys.argv) > 1 else "build"

SH = {}
for a, b in zip("1234567890-=[]\\;'`,./",
                "!@#$%^&*()_+{}|:\"~<>?"):
    SH[a] = b

SCAN = {}
for i, c in enumerate("1234567890-="):
    SCAN[c] = 0x02 + i
for row, base in (("qwertyuiop[]", 0x10), ("asdfghjkl;'`", 0x1E),
                  ("zxcvbnm,./", 0x2C)):
    for i, c in enumerate(row):
        SCAN[c] = base + i
SCAN["\\"] = 0x2B

# rows of (label, ascii, shifted, scan); ascii 0xFF=shift, 0xFE=ctrl
ROWS = [
    [(c, ord(c), ord(SH.get(c, c)), SCAN[c]) for c in "1234567890-="]
    + [("BS", 8, 8, 0x0E), ("ESC", 27, 27, 0x01)],
    [(c, ord(c), ord(c.upper() if c.isalpha() else SH.get(c, c)), SCAN[c])
     for c in "qwertyuiop[]\\"],
    [(c, ord(c), ord(c.upper() if c.isalpha() else SH.get(c, c)), SCAN[c])
     for c in "asdfghjkl;'`"] + [("ENTER", 13, 13, 0x1C)],
    [(c, ord(c), ord(c.upper() if c.isalpha() else SH.get(c, c)), SCAN[c])
     for c in "zxcvbnm,./"] + [("SHIFT", 0xFF, 0xFF, 0), ("CTRL", 0xFE, 0xFE, 0)],
    # F1-F10: BIOS scancodes 3B-44, ASCII 0 (like the arrow keys).
    # F11/F12 (0x85/0x86) need the extended INT 16h API (AH=10h/11h),
    # which the HLE BIOS doesn't implement — deliberately absent.
    [("SPACE", 32, 32, 0x39), ("TAB", 9, 9, 0x0F)]
    + [("F%d" % i, 0, 0, 0x3A + i) for i in range(1, 11)],
]

rows_txt = []
rows_sh = []                 # same rows with shifted glyphs on 1-char keys
grid = [[0xFF] * 64 for _ in range(5)]
keys = []
for r, rowkeys in enumerate(ROWS):
    line = [" "] * 64
    line_sh = [" "] * 64
    x = 1
    for label, a, s, sc in rowkeys:
        idx = len(keys)
        keys.append((r, x, len(label), a, s, sc))
        sh = chr(s) if (len(label) == 1 and s != a and 32 < s < 127) else label
        for i, ch in enumerate(label):
            line[x + i] = ch
            line_sh[x + i] = sh[i]
            grid[r][x + i] = idx
        x += len(label) + 2
    rows_txt.append("".join(line))
    rows_sh.append("".join(line_sh))

# shift delta: (row, col, normal char, shifted char) per differing cell
sdelta = [(r, c, ord(rows_txt[r][c]), ord(rows_sh[r][c]))
          for r in range(5) for c in range(64)
          if rows_txt[r][c] != rows_sh[r][c]]

os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "kbdlayout.asm"), "w") as f:
    f.write("; generated by mkkbd.py\nkbd_rows:\n")
    for t in rows_txt:
        f.write('    .db "%s"\n' % t.replace("\\", "\\\\").replace('"', '\\"'))
    f.write("kbd_rows_sh:\n")   # kbd_color reads these while shift is drawn
    for t in rows_sh:
        f.write('    .db "%s"\n' % t.replace("\\", "\\\\").replace('"', '\\"'))
    f.write("kbd_grid:\n")
    for r in range(5):
        for c0 in range(0, 64, 16):
            f.write("    .db " + ", ".join("$%02X" % v for v in grid[r][c0:c0+16]) + "\n")
    f.write("kbd_keys:\n")
    for k in keys:
        f.write("    .db %d, %d, %d, $%02X, $%02X, $%02X\n" % k)
    f.write(".DEFINE KBD_NKEYS %d\n" % len(keys))
    f.write("kbd_sdelta:\n")   # row $FF terminates (kbd_shift in dosboot.asm)
    for d in sdelta:
        f.write("    .db %d, %d, $%02X, $%02X\n" % d)
    f.write("    .db $FF, $FF, $FF, $FF\n")
print(f"kbdlayout.asm: {len(keys)} keys, {len(sdelta)} shift cells")
